## Data Types

## 1. nameric
age <- 32
print(age)
class(age)

## 2. character
my_name <- "Ploy"
my_university <- 'NIDA'
print(my_name)
print(my_university)
print(my_name);class(my_university)

## 3. logical
result <- 1 + 1 == 2
print(result)
class(result)

## 4. factor
animals <- c("Dog","Cat","Cat","Hippo")
class(animals)

animals <- factor(animals)
class(animals)

## 5. date/time
time_now <- Sys.time()
class(time_now)
